"""Run the development API on the LAN for Expo Go clients."""

from pathlib import Path

import uvicorn


if __name__ == "__main__":
    uvicorn.run(
        "backend.main:app",
        host="0.0.0.0",
        port=8000,
        reload=True,
        reload_dirs=[str(Path(__file__).resolve().parent)],
    )
